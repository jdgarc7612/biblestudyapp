#!/usr/bin/env python3
"""
Build Omeora's section headings from the Berean Standard Bible.

Usage (run from the repo root; uses only the Python standard library):

    python3 -I scripts/bible/build_headings.py SOURCE_DIR

SOURCE_DIR must contain eng-bsb.usfx.xml, the same eBible.org export of the BSB
(via https://github.com/seven1m/open-bibles) that the bundled BSB text is built from,
so every heading lines up with the verses the app shows.

Headings aren't part of Scripture itself; each translation's editors write their own.
The BSB's headings are public domain like the rest of the BSB, and the app shows them
above the same verse in every translation (see data/bible/SOURCES.md).

Output (overwritten):
    data/bible/headings/<book-slug>.json   {"<chapter>": [[verse, "Heading", level], ...]}
    data/bible/headings/loaders.ts          lazy import map used by lib/headings.ts

level: 1 = section heading (s1), 2 = sub-heading (s2, and the Hebrew letters of
Psalm 119), 0 = the five "books" of the Psalms (ms1).
"""

import json
import os
import re
import sys
import xml.etree.ElementTree as ET

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from books import BOOKS  # noqa: E402

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT_DIR = os.path.join(REPO_ROOT, "data", "bible", "headings")
USFM_TO_SLUG = {b[1]: b[0] for b in BOOKS}
ROMAN = {"I": "One", "II": "Two", "III": "Three", "IV": "Four", "V": "Five"}


def local(tag):
    return tag.split("}", 1)[-1]


def text_of(e):
    parts = [e.text or ""]
    for ch in e:
        if local(ch.tag) not in {"f", "x"}:
            parts.append(text_of(ch))
        parts.append(ch.tail or "")
    return " ".join("".join(parts).split())


def heading_for(e):
    """(text, level) when this element is a heading, else None."""
    tag, style = local(e.tag), e.get("style") or ""
    if tag == "s" and style in {"s", "s1", "s2"}:
        return text_of(e), 2 if style == "s2" else 1
    if tag == "p" and style == "ms1":
        m = re.match(r"BOOK\s+([IV]+)$", text_of(e))
        return (f"Book {ROMAN[m.group(1)]}" if m else text_of(e).title()), 0
    if tag == "p" and style == "qa":
        return text_of(e).title(), 2
    return None


def build(path):
    out = {}  # slug -> {chapter: [[verse, text, level]]}
    stats = {"headings": 0, "mid_verse": []}
    book = chapter = None
    pending = []
    in_verse = False
    verse = None

    for e in ET.parse(path).getroot().iter():
        tag = local(e.tag)
        if tag == "book":
            book = USFM_TO_SLUG.get(e.get("id"))
            chapter, pending, in_verse = None, [], False
            if book:
                out.setdefault(book, {})
        elif not book:
            continue
        elif tag == "c":
            chapter, pending, in_verse = int(e.get("id")), [], False
        elif tag == "v":
            m = re.match(r"(\d+)", e.get("id") or "")
            verse = int(m.group(1)) if m else None
            if pending and chapter and verse:
                out[book].setdefault(str(chapter), []).extend([[verse, t, lv] for t, lv in pending])
                stats["headings"] += len(pending)
            pending, in_verse = [], True
        elif tag == "ve":
            in_verse = False
        else:
            h = heading_for(e)
            if h and h[0] and chapter:
                if in_verse:
                    # A heading inside a verse (the Song of Songs' speaker labels). Moving it to the
                    # next verse would credit the wrong speaker, so it's left out.
                    stats["mid_verse"].append(f"{book} {chapter}:{verse} {h[0]}")
                else:
                    pending.append(h)

    return out, stats


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    out, stats = build(os.path.join(sys.argv[1], "eng-bsb.usfx.xml"))
    os.makedirs(OUT_DIR, exist_ok=True)
    for slug, *_ in BOOKS:
        with open(os.path.join(OUT_DIR, f"{slug}.json"), "w", encoding="utf-8") as f:
            json.dump(out.get(slug, {}), f, ensure_ascii=False, separators=(",", ":"))
    lines = [
        "// Generated by scripts/bible/build_headings.py. Do not edit by hand.",
        "/* eslint-disable */",
        'import type { BookHeadings } from "../../../lib/headings";',
        "",
        "type Loader = () => Promise<{ default: BookHeadings }>;",
        "",
        "export const headingLoaders: Record<string, Loader> = {",
    ]
    for slug, *_ in BOOKS:
        lines.append(
            f'  "{slug}": () => import("./{slug}.json") as unknown as Promise<{{ default: BookHeadings }}>,'
        )
    lines += ["};", ""]
    with open(os.path.join(OUT_DIR, "loaders.ts"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"{stats['headings']} headings in {len(out)} books")
    print(f"{len(stats['mid_verse'])} headings sat inside a verse (left out):")
    for line in stats["mid_verse"]:
        print("  ", line)


if __name__ == "__main__":
    main()
