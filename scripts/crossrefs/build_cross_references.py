#!/usr/bin/env python3
"""
Build Omeora's cross-reference files from the OpenBible.info dataset.

Usage (run from the repo root; standard library only):

    python3 -I scripts/crossrefs/build_cross_references.py PATH/TO/cross_references.txt

The source is OpenBible.info's "Bible Cross References" (https://www.openbible.info/labs/cross-references/),
licensed CC BY. It is a tab-separated file: From Verse, To Verse, Votes (OSIS references).
It is derived from the Treasury of Scripture Knowledge, with votes from readers on how helpful
each link is. A copy is also kept at github.com/scrollmapper/bible_databases
(sources/extras/cross_references.txt).

Output (overwritten):
    data/crossrefs/<book-slug>.json   {"c": [["<refs for verse 1>", ...], ...]}
    data/crossrefs/loaders.ts         lazy import map used by lib/cross-references.ts

Each verse's refs are one space-separated string, best first. A ref is
"<book index>.<chapter>.<verse>", with an optional end: "-<verse>" (same chapter) or
"-<chapter>.<verse>". The book index is the position in data/bible/books.json (0 = Genesis).
"""

import json
import os
import sys
from collections import defaultdict

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT_DIR = os.path.join(REPO_ROOT, "data", "crossrefs")

# OSIS book codes in canonical order, matching data/bible/books.json.
OSIS = (
    "Gen Exod Lev Num Deut Josh Judg Ruth 1Sam 2Sam 1Kgs 2Kgs 1Chr 2Chr Ezra Neh Esth Job Ps Prov "
    "Eccl Song Isa Jer Lam Ezek Dan Hos Joel Amos Obad Jonah Mic Nah Hab Zeph Hag Zech Mal "
    "Matt Mark Luke John Acts Rom 1Cor 2Cor Gal Eph Phil Col 1Thess 2Thess 1Tim 2Tim Titus Phlm "
    "Heb Jas 1Pet 2Pet 1John 2John 3John Jude Rev"
).split()

# Keep the most helpful links only: readers' votes at or above this, at most this many per verse.
MIN_VOTES = 2
MAX_PER_VERSE = 12


def parse(ref):
    book, chapter, verse = ref.split(".")
    return OSIS.index(book), int(chapter), int(verse)


def encode(target):
    if "-" in target:
        start, end = target.split("-")
    else:
        start, end = target, target
    b, c, v = parse(start)
    eb, ec, ev = parse(end)
    out = f"{b}.{c}.{v}"
    if eb != b or (ec, ev) == (c, v):
        return out  # cross-book ranges are rare; keep the starting verse
    return out + (f"-{ev}" if ec == c else f"-{ec}.{ev}")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    assert len(OSIS) == 66
    books = json.load(open(os.path.join(REPO_ROOT, "data", "bible", "books.json"), encoding="utf-8"))
    assert len(books) == 66

    links = defaultdict(list)  # (book, chapter, verse) -> [(votes, encoded)]
    with open(sys.argv[1], encoding="utf-8") as fh:
        next(fh)
        for line in fh:
            parts = line.rstrip("\n").split("\t")
            if len(parts) < 3:
                continue
            votes = int(parts[2])
            if votes < MIN_VOTES:
                continue
            links[parse(parts[0])].append((votes, encode(parts[1])))

    os.makedirs(OUT_DIR, exist_ok=True)
    total = 0
    for bi, book in enumerate(books):
        chapters = []
        for c in range(1, book["chapters"] + 1):
            verses = [k[2] for k in links if k[0] == bi and k[1] == c]
            last = max(verses, default=0)
            row = []
            for v in range(1, last + 1):
                best = sorted(links.get((bi, c, v), []), key=lambda x: -x[0])
                seen, refs = set(), []
                for _, r in best:
                    if r not in seen:
                        seen.add(r)
                        refs.append(r)
                    if len(refs) == MAX_PER_VERSE:
                        break
                total += len(refs)
                row.append(" ".join(refs))
            chapters.append(row)
        with open(os.path.join(OUT_DIR, f"{book['id']}.json"), "w", encoding="utf-8") as fh:
            json.dump({"c": chapters}, fh, separators=(",", ":"))

    lines = [
        "// Generated by scripts/crossrefs/build_cross_references.py. Do not edit by hand.",
        "/* eslint-disable */",
        "export type CrossRefBook = { c: string[][] };",
        "type Loader = () => Promise<{ default: CrossRefBook }>;",
        "",
        "export const crossRefLoaders: Record<string, Loader> = {",
    ]
    for book in books:
        lines.append(
            f'  "{book["id"]}": () => import("./{book["id"]}.json") as unknown as Promise<{{ default: CrossRefBook }}>,'
        )
    lines.append("};")
    with open(os.path.join(OUT_DIR, "loaders.ts"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"Wrote {total} cross-references for 66 books to {OUT_DIR}")


if __name__ == "__main__":
    main()
